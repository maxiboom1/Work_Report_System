export let workerLanguage = CURRENT_LANGUAGE;

export function t(key) {
  return STRINGS[workerLanguage]?.[key] || STRINGS.en[key] || key;
}

export function setWorkerLanguage(language) {
  workerLanguage = language === "en" ? "en" : "he";
  localStorage.setItem(STORAGE_KEY, workerLanguage);
  applyDocumentLanguage();
  updateStaticText();
}

export function applyDocumentLanguage() {
  document.documentElement.lang = workerLanguage;
  document.documentElement.dir = workerLanguage === "he" ? "rtl" : "ltr";
  document.body.dataset.workerLanguage = workerLanguage;
}

export function updateStaticText(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.dataset.i18nTitle));
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  });
  document.querySelectorAll("[data-worker-lang]").forEach((button) => {
    button.classList.toggle("active", button.dataset.workerLang === workerLanguage);
    button.setAttribute("aria-pressed", button.dataset.workerLang === workerLanguage ? "true" : "false");
  });
}

export function initWorkerI18n(onChange) {
  const savedLanguage = localStorage.getItem(STORAGE_KEY);
  workerLanguage = savedLanguage === "en" ? "en" : CURRENT_LANGUAGE;
  localStorage.setItem(STORAGE_KEY, workerLanguage);
  applyDocumentLanguage();
  document.querySelectorAll("[data-worker-lang]").forEach((button) => {
    button.addEventListener("click", () => {
      setWorkerLanguage(button.dataset.workerLang);
      if (typeof onChange === "function") onChange(workerLanguage);
    });
  });
  updateStaticText();
}
